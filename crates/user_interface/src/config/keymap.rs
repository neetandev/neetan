/// Encodes a PC-88 keyboard matrix position as `row << 3 | column`. The high bit
/// stays clear so the forwarding layer can set it to mark a key release.
const fn pc88_cell(row: u8, column: u8) -> u8 {
    (row << 3) | column
}

