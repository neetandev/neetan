//! machine-native key on the right. The parsers here resolve the right-hand name
//! into the raw native code for a target family, bypassing the neutral host-key
//! path. This namespace is machine-specific, so every family has its own table.
//! Each family exposes a single `*_from_name` table; `parse_key_binding` routes a
//! target to its table and pairs the result with the host scancode.

use machine_factory::config::Target;
