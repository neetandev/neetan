//! FM-7 keyboard translation tables.
//!
//! Each table maps an FM-7 physical scancode (`0x00..=0x66`) to the 9-bit F-BASIC
//! keycode for one modifier combination. A `0x0000` entry means the key produces
//! no code in that combination. The physical scancode is the machine's canonical
//! key identifier: the application key map translates host keys into these
//! scancodes, so the value handed to the keyboard is already a physical scancode.
//!
//! Function keys F1..F10 map to keycodes `0x0101..=0x010A`, whose ninth bit is
//! why the keycode latch is nine bits wide.
//!
//! Two table sets exist: the standard F-BASIC set and the FM-16beta compatible
//! set selected through the FM-77AV encoder's scancode-mode command. The
//! FM-16beta set differs mainly in the editing-key block, which reports 9-bit
//! codes of its own instead of control characters.

/// Number of distinct FM-7 physical scancodes (`0x00..=0x66`).
pub(super) const SCANCODE_COUNT: usize = 0x67;

/// The modifier-selected keycode tables of one reporting mode.
pub(super) struct KeycodeTables {
    pub(super) normal: &'static [u16; SCANCODE_COUNT],
    pub(super) shift: &'static [u16; SCANCODE_COUNT],
    pub(super) ctrl: &'static [u16; SCANCODE_COUNT],
    pub(super) ctrl_shift: &'static [u16; SCANCODE_COUNT],
    pub(super) graph: &'static [u16; SCANCODE_COUNT],
    pub(super) graph_shift: &'static [u16; SCANCODE_COUNT],
    pub(super) kana: &'static [u16; SCANCODE_COUNT],
    pub(super) kana_shift: &'static [u16; SCANCODE_COUNT],
}

