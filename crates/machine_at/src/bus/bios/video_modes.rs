/// Text and 16-color planar modes DAC palette.
pub(super) const PALETTE_EGA: [u8; 768] = {
    let mut palette = [0u8; 768];
    // The 64 EGA base colors: bit 2/5 of the index drive the red, bit 1/4 the
    // green, bit 0/3 the blue component (0x15 low, 0x2A high amplitude).
    let mut index = 0usize;
    while index < 64 {
        let red = ((index >> 2) & 0x01) * 0x2A + ((index >> 5) & 0x01) * 0x15;
        let green = ((index >> 1) & 0x01) * 0x2A + ((index >> 4) & 0x01) * 0x15;
        let blue = (index & 0x01) * 0x2A + ((index >> 3) & 0x01) * 0x15;
        palette[index * 3] = red as u8;
        palette[index * 3 + 1] = green as u8;
        palette[index * 3 + 2] = blue as u8;
        index += 1;
    }
    palette
};

