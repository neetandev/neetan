//! VGA mode register tables and per-mode BIOS parameters for INT 10h.
//!
//! Every register file, palette and BDA value was captured from the real
//! ET4000AX VGA BIOS after the corresponding INT 10h mode set. Modes 00h,
//! 02h and 05h program register files identical to modes 01h, 03h and 04h
//! (they only differ on the composite color burst, which the RGB pipeline
//! ignores); the shared consts carry both mode numbers.

use common::TraceSink;

use super::super::AtBus;

/// One VGA register file: misc output, sequencer, CRTC 0x00-0x18, graphics
/// controller, attribute controller, the full 256-entry DAC palette and the
/// segment select.
pub(crate) struct VgaModeRegisters {
    /// Miscellaneous output register.
    pub misc: u8,
    /// Sequencer registers 0x00-0x07.
    pub seq: [u8; 8],
    /// CRTC registers 0x00-0x18.
    pub crtc: [u8; 0x19],
    /// Graphics controller registers 0x00-0x08.
    pub gc: [u8; 9],
    /// Attribute controller registers 0x00-0x16.
    pub atc: [u8; 0x17],
    /// Full 256-entry DAC palette (6-bit components).
    pub palette: &'static [u8; 768],
    /// ET4000 segment select register.
    pub segment_select: u8,
}

/// ET4000 extended CRTC registers the BIOS programs identically in every mode
/// (RAS/CAS 0x32, auxiliary 0x34, system configuration 0x36/0x37).
pub(super) const EXTENDED_CRTC: [(u8, u8); 4] =
    [(0x32, 0x28), (0x34, 0x08), (0x36, 0x43), (0x37, 0x0F)];

/// Rendering family that selects the pixel and glyph codec of a mode.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(super) enum ModeFamily {
    /// Alphanumeric modes with character/attribute cells in the regen buffer.
    Text,
    /// CGA 640x200 2-color interleaved graphics.
    Cga2,
    /// CGA 320x200 4-color interleaved graphics.
    Cga4,
    /// EGA/VGA 16-color planar graphics.
    Planar,
    /// Packed 8-bit-per-pixel graphics (mode 13h and the Tseng SVGA modes).
    Packed,
}

/// ROM font selection for INT 43h and the font services.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(super) enum ModeFont {
    /// The 8x8 CGA/BIOS font.
    Font8x8,
    /// The 8x14 EGA font.
    Font8x14,
    /// The 8x16 VGA font.
    Font8x16,
}

/// Everything the mode set and the INT 10h services need to know about one
/// video mode.
pub(super) struct VideoModeEntry {
    /// BIOS mode number.
    pub mode: u8,
    /// The captured register file the mode programs.
    pub registers: &'static VgaModeRegisters,
    /// Pixel and glyph codec family.
    pub family: ModeFamily,
    /// Font INT 43h points at after the mode set (captured behavior).
    pub font: ModeFont,
    /// Text columns (BDA 40:4A).
    pub columns: u16,
    /// Displayed text rows minus one (BDA 40:84).
    pub rows_minus_one: u8,
    /// Character cell height in scan lines (BDA 40:85).
    pub char_height: u16,
    /// Display page size in bytes (BDA 40:4C).
    pub page_size: u16,
    /// Number of display pages AH=05h may select.
    pub page_count: u8,
    /// Number of colors AH=1Bh reports (0 in the monochrome modes).
    pub color_count: u16,
    /// Scan line code AH=1Bh reports (0=200, 1=350, 2=400, 3=480, 5=600).
    pub scan_line_code: u8,
    /// Physical base of the regen buffer (0xB8000, 0xB0000 or 0xA0000).
    pub regen_base: u32,
    /// CGA mode select register image (BDA 40:65).
    pub mode_select: u8,
    /// CGA palette register image (BDA 40:66).
    pub cga_palette: u8,
    /// Video control bits (BDA 40:87; bit 7, the no-clear flag, is dynamic).
    pub video_control: u8,
    /// Feature switches value (BDA 40:88).
    pub switches: u8,
    /// Pixel width in graphics modes (0 in text modes).
    pub width: u16,
    /// Pixel height in graphics modes (0 in text modes).
    pub height: u16,
}

impl VideoModeEntry {
    /// CRTC index port of the mode (BDA 40:63): 0x3D4 color, 0x3B4 mono.
    pub(super) fn crtc_base(&self) -> u16 {
        if self.registers.misc & 0x01 != 0 {
            0x3D4
        } else {
            0x3B4
        }
    }
}

impl ModeFont {
    /// VGA ROM metadata word holding the font's ROM offset.
    pub(super) fn metadata_offset(self) -> usize {
        match self {
            ModeFont::Font8x8 => VGA_METADATA_FONT_8X8,
            ModeFont::Font8x14 => VGA_METADATA_FONT_8X14,
            ModeFont::Font8x16 => VGA_METADATA_FONT_8X16,
        }
    }

    /// Glyph height in bytes.
    pub(super) fn height(self) -> u32 {
        match self {
            ModeFont::Font8x8 => 8,
            ModeFont::Font8x14 => 14,
            ModeFont::Font8x16 => 16,
        }
    }
}

/// Real-mode segment of the VGA BIOS stub ROM.
pub(super) const VGA_BIOS_SEGMENT: u16 = 0xC000;
/// VGA ROM metadata word: 8x8 font offset (2048 bytes).
pub(super) const VGA_METADATA_FONT_8X8: usize = 0x10;
/// VGA ROM metadata word: 8x8 font upper-half offset (the INT 1Fh target).
pub(super) const VGA_METADATA_FONT_8X8_UPPER: usize = 0x12;
/// VGA ROM metadata word: 8x14 font offset (3584 bytes).
pub(super) const VGA_METADATA_FONT_8X14: usize = 0x14;
/// VGA ROM metadata word: 8x16 font offset (4096 bytes).
pub(super) const VGA_METADATA_FONT_8X16: usize = 0x16;
/// VGA ROM metadata word: AH=1Bh static functionality table offset (16 bytes).
pub(super) const VGA_METADATA_FUNCTIONALITY: usize = 0x18;
/// VGA ROM metadata word: video parameter table offset.
pub(crate) const VGA_METADATA_VIDEO_PARAMETER_TABLE: usize = 0x1A;
/// VGA ROM metadata word: video parameter table entry count.
pub(crate) const VGA_METADATA_VIDEO_PARAMETER_COUNT: usize = 0x1C;
/// VGA ROM metadata word: video save pointer table offset (28 bytes).
pub(crate) const VGA_METADATA_SAVE_POINTER_TABLE: usize = 0x1E;

impl<T: TraceSink> AtBus<T> {
    /// Reads a little-endian word from the VGA stub ROM metadata header.
    pub(super) fn vga_rom_metadata_word(&self, offset: usize) -> u16 {
        u16::from(self.memory.vga_bios_byte(offset))
            | (u16::from(self.memory.vga_bios_byte(offset + 1)) << 8)
    }
}

/// Looks up the mode table entry for a BIOS mode number.
pub(super) fn mode_entry(mode: u8) -> Option<&'static VideoModeEntry> {
    match mode {
        0x00 => Some(&ENTRY_00H),
        0x01 => Some(&ENTRY_01H),
        0x02 => Some(&ENTRY_02H),
        0x03 => Some(&ENTRY_03H),
        0x04 => Some(&ENTRY_04H),
        0x05 => Some(&ENTRY_05H),
        0x06 => Some(&ENTRY_06H),
        0x07 => Some(&ENTRY_07H),
        0x0D => Some(&ENTRY_0DH),
        0x0E => Some(&ENTRY_0EH),
        0x0F => Some(&ENTRY_0FH),
        0x10 => Some(&ENTRY_10H),
        0x11 => Some(&ENTRY_11H),
        0x12 => Some(&ENTRY_12H),
        0x13 => Some(&ENTRY_13H),
        0x2E => Some(&ENTRY_2EH),
        0x2F => Some(&ENTRY_2FH),
        0x30 => Some(&ENTRY_30H),
        _ => None,
    }
}

