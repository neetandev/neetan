//! INT 10h graphics services: pixel read/write per mode family, glyph
//! rendering and read-back through the INT 43h/1Fh fonts, and window scroll
//! in a planar mode.

use common::Bus;

use super::{RESULT, boot_and_run, create_machine_dx50, read_ram_u8, read_ram_u16};

/// Cycle budget for one injected INT 10h program.
const BUDGET: u64 = 16_000_000;

/// Mode 04h: pixel writes at the interleave corners, an XOR write, and the
/// read-backs stored to the result area.
#[rustfmt::skip]
const CGA4_PIXEL_CODE: &[u8] = &[
    0xB8, 0x04, 0x00,       // MOV AX, 0x0004
    0xCD, 0x10,             // INT 10h
    0xB8, 0x01, 0x0C,       // MOV AX, 0x0C01 color 1
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xB9, 0x00, 0x00,       // MOV CX, 0 (x)
    0xBA, 0x00, 0x00,       // MOV DX, 0 (y)
    0xCD, 0x10,             // INT 10h
    0xB8, 0x02, 0x0C,       // MOV AX, 0x0C02 color 2
    0xB9, 0x03, 0x00,       // MOV CX, 3
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xB8, 0x03, 0x0C,       // MOV AX, 0x0C03 color 3
    0xB9, 0x00, 0x00,       // MOV CX, 0
    0xBA, 0x01, 0x00,       // MOV DX, 1
    0xCD, 0x10,             // INT 10h
    0xB8, 0x02, 0x0C,       // MOV AX, 0x0C02 color 2
    0xB9, 0x3F, 0x01,       // MOV CX, 319
    0xBA, 0xC7, 0x00,       // MOV DX, 199
    0xCD, 0x10,             // INT 10h
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x00, 0x00,       // MOV CX, 0
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xA2, 0x00, 0x06,       // MOV [0x0600], AL
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x03, 0x00,       // MOV CX, 3
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xA2, 0x01, 0x06,       // MOV [0x0601], AL
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x00, 0x00,       // MOV CX, 0
    0xBA, 0x01, 0x00,       // MOV DX, 1
    0xCD, 0x10,             // INT 10h
    0xA2, 0x02, 0x06,       // MOV [0x0602], AL
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x3F, 0x01,       // MOV CX, 319
    0xBA, 0xC7, 0x00,       // MOV DX, 199
    0xCD, 0x10,             // INT 10h
    0xA2, 0x03, 0x06,       // MOV [0x0603], AL
    // XOR color 3 over the color 1 pixel at (0,0): 1 ^ 3 = 2.
    0xB8, 0x83, 0x0C,       // MOV AX, 0x0C83
    0xB9, 0x00, 0x00,       // MOV CX, 0
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x00, 0x00,       // MOV CX, 0
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xA2, 0x04, 0x06,       // MOV [0x0604], AL
    0xF4,                   // HLT
];

#[test]
fn cga4_pixel_round_trip_and_interleave() {
    let mut machine = create_machine_dx50();
    boot_and_run(&mut machine, CGA4_PIXEL_CODE, &[], BUDGET);
    assert_eq!(read_ram_u8(&machine, RESULT), 0x01);
    assert_eq!(read_ram_u8(&machine, RESULT + 1), 0x02);
    assert_eq!(read_ram_u8(&machine, RESULT + 2), 0x03);
    assert_eq!(read_ram_u8(&machine, RESULT + 3), 0x02);
    assert_eq!(read_ram_u8(&machine, RESULT + 4), 0x02);
    // Even scanline 0 lands in the first interleave bank. The XOR turned
    // pixel (0,0) into color 2, pixel (3,0) is color 2: 10 000010b.
    assert_eq!(machine.bus.read_byte(0xB8000), 0x82);
    // Odd scanline 1 lands in the 0x2000 bank: color 3 at pixel 0.
    assert_eq!(machine.bus.read_byte(0xBA000), 0xC0);
}

/// Mode 12h: two adjacent pixels, an XOR write and a far corner write with
/// the read-backs stored.
#[rustfmt::skip]
const PLANAR_PIXEL_CODE: &[u8] = &[
    0xB8, 0x12, 0x00,       // MOV AX, 0x0012
    0xCD, 0x10,             // INT 10h
    0xB8, 0x05, 0x0C,       // MOV AX, 0x0C05 color 5
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xB9, 0x08, 0x00,       // MOV CX, 8
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xB8, 0x0A, 0x0C,       // MOV AX, 0x0C0A color 10
    0xB9, 0x09, 0x00,       // MOV CX, 9
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    // XOR color 6 over the color 5 pixel at (8,0): 5 ^ 6 = 3.
    0xB8, 0x86, 0x0C,       // MOV AX, 0x0C86
    0xB9, 0x08, 0x00,       // MOV CX, 8
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xB8, 0x0F, 0x0C,       // MOV AX, 0x0C0F color 15
    0xB9, 0x7F, 0x02,       // MOV CX, 639
    0xBA, 0xDF, 0x01,       // MOV DX, 479
    0xCD, 0x10,             // INT 10h
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x08, 0x00,       // MOV CX, 8
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xA2, 0x00, 0x06,       // MOV [0x0600], AL
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x09, 0x00,       // MOV CX, 9
    0xBA, 0x00, 0x00,       // MOV DX, 0
    0xCD, 0x10,             // INT 10h
    0xA2, 0x01, 0x06,       // MOV [0x0601], AL
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xB9, 0x7F, 0x02,       // MOV CX, 639
    0xBA, 0xDF, 0x01,       // MOV DX, 479
    0xCD, 0x10,             // INT 10h
    0xA2, 0x02, 0x06,       // MOV [0x0602], AL
    0xF4,                   // HLT
];

#[test]
fn planar_pixel_isolation_and_xor() {
    let mut machine = create_machine_dx50();
    boot_and_run(&mut machine, PLANAR_PIXEL_CODE, &[], BUDGET);
    assert_eq!(read_ram_u8(&machine, RESULT), 0x03);
    // The adjacent pixel in the same byte was untouched by the bit mask.
    assert_eq!(read_ram_u8(&machine, RESULT + 1), 0x0A);
    assert_eq!(read_ram_u8(&machine, RESULT + 2), 0x0F);
}

