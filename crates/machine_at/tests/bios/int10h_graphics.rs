/// Writes glyph 'A' at (2,3) in modes 06h/0Dh/13h, code 0xB0 in mode 04h,
/// and stores each AH=08h read-back.
#[rustfmt::skip]
const GLYPH_ROUND_TRIP_CODE: &[u8] = &[
    // Mode 06h, 'A' color 1.
    0xB8, 0x06, 0x00,       // MOV AX, 0x0006
    0xCD, 0x10,             // INT 10h
    0xB4, 0x02,             // MOV AH, 0x02
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xBA, 0x03, 0x02,       // MOV DX, 0x0203
    0xCD, 0x10,             // INT 10h
    0xB8, 0x41, 0x09,       // MOV AX, 0x0941 'A'
    0xBB, 0x01, 0x00,       // MOV BX, 0x0001
    0xB9, 0x01, 0x00,       // MOV CX, 0x0001
    0xCD, 0x10,             // INT 10h
    0xB4, 0x08,             // MOV AH, 0x08
    0xB7, 0x00,             // MOV BH, 0x00
    0xCD, 0x10,             // INT 10h
    0xA3, 0x00, 0x06,       // MOV [0x0600], AX
    // Mode 0Dh, 'A' color 12.
    0xB8, 0x0D, 0x00,       // MOV AX, 0x000D
    0xCD, 0x10,             // INT 10h
    0xB4, 0x02,             // MOV AH, 0x02
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xBA, 0x03, 0x02,       // MOV DX, 0x0203
    0xCD, 0x10,             // INT 10h
    0xB8, 0x41, 0x09,       // MOV AX, 0x0941 'A'
    0xBB, 0x0C, 0x00,       // MOV BX, 0x000C
    0xB9, 0x01, 0x00,       // MOV CX, 0x0001
    0xCD, 0x10,             // INT 10h
    0xB4, 0x08,             // MOV AH, 0x08
    0xB7, 0x00,             // MOV BH, 0x00
    0xCD, 0x10,             // INT 10h
    0xA3, 0x02, 0x06,       // MOV [0x0602], AX
    // Mode 13h, 'A' color 0x28.
    0xB8, 0x13, 0x00,       // MOV AX, 0x0013
    0xCD, 0x10,             // INT 10h
    0xB4, 0x02,             // MOV AH, 0x02
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xBA, 0x03, 0x02,       // MOV DX, 0x0203
    0xCD, 0x10,             // INT 10h
    0xB8, 0x41, 0x09,       // MOV AX, 0x0941 'A'
    0xBB, 0x28, 0x00,       // MOV BX, 0x0028
    0xB9, 0x01, 0x00,       // MOV CX, 0x0001
    0xCD, 0x10,             // INT 10h
    0xB4, 0x08,             // MOV AH, 0x08
    0xB7, 0x00,             // MOV BH, 0x00
    0xCD, 0x10,             // INT 10h
    0xA3, 0x04, 0x06,       // MOV [0x0604], AX
    // Mode 04h, code 0xB0 through the INT 1Fh upper font, color 3.
    0xB8, 0x04, 0x00,       // MOV AX, 0x0004
    0xCD, 0x10,             // INT 10h
    0xB4, 0x02,             // MOV AH, 0x02
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xBA, 0x03, 0x02,       // MOV DX, 0x0203
    0xCD, 0x10,             // INT 10h
    0xB8, 0xB0, 0x09,       // MOV AX, 0x09B0
    0xBB, 0x03, 0x00,       // MOV BX, 0x0003
    0xB9, 0x01, 0x00,       // MOV CX, 0x0001
    0xCD, 0x10,             // INT 10h
    0xB4, 0x08,             // MOV AH, 0x08
    0xB7, 0x00,             // MOV BH, 0x00
    0xCD, 0x10,             // INT 10h
    0xA3, 0x06, 0x06,       // MOV [0x0606], AX
    0xF4,                   // HLT
];

#[test]
fn glyph_write_and_read_back_per_family() {
    let mut machine = create_machine_dx50();
    boot_and_run(&mut machine, GLYPH_ROUND_TRIP_CODE, &[], BUDGET);
    assert_eq!(read_ram_u16(&machine, RESULT), 0x0041, "mode 06h");
    assert_eq!(read_ram_u16(&machine, RESULT + 2), 0x0041, "mode 0Dh");
    assert_eq!(read_ram_u16(&machine, RESULT + 4), 0x0041, "mode 13h");
    assert_eq!(read_ram_u16(&machine, RESULT + 6), 0x00B0, "mode 04h");
}

/// Mode 0Dh: 'A' on row 1, scroll the full window up one line with fill
/// color 3, read the glyph on row 0 and a pixel of the freed bottom row.
#[rustfmt::skip]
const GRAPHICS_SCROLL_CODE: &[u8] = &[
    0xB8, 0x0D, 0x00,       // MOV AX, 0x000D
    0xCD, 0x10,             // INT 10h
    0xB4, 0x02,             // MOV AH, 0x02
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xBA, 0x00, 0x01,       // MOV DX, 0x0100
    0xCD, 0x10,             // INT 10h
    0xB8, 0x41, 0x09,       // MOV AX, 0x0941 'A'
    0xBB, 0x0F, 0x00,       // MOV BX, 0x000F
    0xB9, 0x01, 0x00,       // MOV CX, 0x0001
    0xCD, 0x10,             // INT 10h
    0xB8, 0x01, 0x06,       // MOV AX, 0x0601
    0xB7, 0x03,             // MOV BH, 0x03
    0xB9, 0x00, 0x00,       // MOV CX, 0x0000
    0xBA, 0x27, 0x18,       // MOV DX, 0x1827
    0xCD, 0x10,             // INT 10h
    0xB4, 0x02,             // MOV AH, 0x02
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xBA, 0x00, 0x00,       // MOV DX, 0x0000
    0xCD, 0x10,             // INT 10h
    0xB4, 0x08,             // MOV AH, 0x08
    0xB7, 0x00,             // MOV BH, 0x00
    0xCD, 0x10,             // INT 10h
    0xA3, 0x00, 0x06,       // MOV [0x0600], AX
    0xB8, 0x00, 0x0D,       // MOV AX, 0x0D00
    0xBB, 0x00, 0x00,       // MOV BX, 0x0000
    0xB9, 0x00, 0x00,       // MOV CX, 0 (x)
    0xBA, 0xC4, 0x00,       // MOV DX, 196 (y in the freed bottom row)
    0xCD, 0x10,             // INT 10h
    0xA2, 0x02, 0x06,       // MOV [0x0602], AL
    0xF4,                   // HLT
];

#[test]
fn graphics_scroll_moves_glyph_rows() {
    let mut machine = create_machine_dx50();
    boot_and_run(&mut machine, GRAPHICS_SCROLL_CODE, &[], BUDGET);
    // The glyph written on row 1 arrived on row 0.
    assert_eq!(read_ram_u16(&machine, RESULT), 0x0041);
    // The freed bottom row was filled with color 3.
    assert_eq!(read_ram_u8(&machine, RESULT + 2), 0x03);
}
